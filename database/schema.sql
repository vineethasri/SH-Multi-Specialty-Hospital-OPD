-- SH Multi-Specialty Hospital OPD Management System
-- Target RDBMS: MySQL 8.4
-- Normalized Relational Schema

CREATE DATABASE IF NOT EXISTS sh_hospital_opd
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE sh_hospital_opd;

CREATE TABLE IF NOT EXISTS Roles (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    Name VARCHAR(50) NOT NULL UNIQUE,
    Description VARCHAR(250) NOT NULL DEFAULT '',
    CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UpdatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Users (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    RoleId INT NOT NULL,
    FullName VARCHAR(150) NOT NULL,
    Email VARCHAR(160) NOT NULL UNIQUE,
    PhoneNumber VARCHAR(25) NOT NULL,
    PasswordHash VARCHAR(255) NOT NULL,
    IsActive TINYINT(1) NOT NULL DEFAULT 1,
    LastLoginAt DATETIME(6) NULL,
    CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UpdatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    INDEX IX_Users_PhoneNumber (PhoneNumber),
    CONSTRAINT FK_Users_Roles FOREIGN KEY (RoleId) REFERENCES Roles(Id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Departments (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    Code VARCHAR(20) NOT NULL UNIQUE,
    Name VARCHAR(120) NOT NULL UNIQUE,
    Description VARCHAR(600) NOT NULL DEFAULT '',
    FloorLocation VARCHAR(80) NOT NULL DEFAULT '',
    ConsultationFeeDefault DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    IsActive TINYINT(1) NOT NULL DEFAULT 1,
    CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UpdatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Doctors (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    UserId INT NOT NULL UNIQUE,
    DepartmentId INT NOT NULL,
    DoctorCode VARCHAR(30) NOT NULL UNIQUE,
    Specialization VARCHAR(150) NOT NULL,
    Qualification VARCHAR(150) NOT NULL,
    RegistrationNumber VARCHAR(80) NOT NULL UNIQUE,
    ExperienceYears INT NOT NULL DEFAULT 0,
    ConsultationFee DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    Bio VARCHAR(1000) NOT NULL DEFAULT '',
    RoomNumber VARCHAR(30) NOT NULL DEFAULT '',
    AverageConsultationMinutes INT NOT NULL DEFAULT 15,
    IsAvailableForOnlineBooking TINYINT(1) NOT NULL DEFAULT 1,
    IsActive TINYINT(1) NOT NULL DEFAULT 1,
    CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UpdatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    CONSTRAINT FK_Doctors_Users FOREIGN KEY (UserId) REFERENCES Users(Id) ON DELETE RESTRICT,
    CONSTRAINT FK_Doctors_Departments FOREIGN KEY (DepartmentId) REFERENCES Departments(Id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS DoctorSchedules (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    DoctorId INT NOT NULL,
    DayOfWeek INT NOT NULL,
    StartTime TIME(6) NOT NULL,
    EndTime TIME(6) NOT NULL,
    SlotDurationMinutes INT NOT NULL DEFAULT 15,
    MaxPatientsPerSlot INT NOT NULL DEFAULT 1,
    IsActive TINYINT(1) NOT NULL DEFAULT 1,
    CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UpdatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    INDEX IX_DoctorSchedules_Doc_Day (DoctorId, DayOfWeek, StartTime),
    CONSTRAINT FK_DoctorSchedules_Doctors FOREIGN KEY (DoctorId) REFERENCES Doctors(Id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Patients (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    UserId INT NULL UNIQUE,
    PatientCode VARCHAR(30) NOT NULL UNIQUE,
    FirstName VARCHAR(80) NOT NULL,
    LastName VARCHAR(80) NOT NULL,
    FullName VARCHAR(165) NOT NULL,
    DateOfBirth DATE NOT NULL,
    Gender VARCHAR(20) NOT NULL,
    BloodGroup VARCHAR(10) NULL,
    PhoneNumber VARCHAR(25) NOT NULL,
    Email VARCHAR(160) NULL,
    Address VARCHAR(300) NULL,
    City VARCHAR(100) NULL,
    EmergencyContactName VARCHAR(120) NULL,
    EmergencyContactPhone VARCHAR(25) NULL,
    Allergies VARCHAR(500) NULL,
    ChronicConditions VARCHAR(500) NULL,
    CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UpdatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    INDEX IX_Patients_PhoneNumber (PhoneNumber),
    INDEX IX_Patients_FullName (FullName),
    CONSTRAINT FK_Patients_Users FOREIGN KEY (UserId) REFERENCES Users(Id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Appointments (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    AppointmentNumber VARCHAR(30) NOT NULL UNIQUE,
    PatientId INT NOT NULL,
    DoctorId INT NOT NULL,
    DepartmentId INT NOT NULL,
    AppointmentDate DATE NOT NULL,
    StartTime TIME(6) NOT NULL,
    EndTime TIME(6) NOT NULL,
    BookingSource VARCHAR(20) NOT NULL,
    Status VARCHAR(25) NOT NULL,
    ReasonForVisit VARCHAR(500) NOT NULL,
    CancellationReason VARCHAR(500) NULL,
    BookedByUserId INT NULL,
    CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UpdatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    INDEX IX_Appointments_Doc_Date (DoctorId, AppointmentDate, StartTime),
    INDEX IX_Appointments_Pat_Date (PatientId, AppointmentDate),
    CONSTRAINT FK_Appointments_Patients FOREIGN KEY (PatientId) REFERENCES Patients(Id) ON DELETE RESTRICT,
    CONSTRAINT FK_Appointments_Doctors FOREIGN KEY (DoctorId) REFERENCES Doctors(Id) ON DELETE RESTRICT,
    CONSTRAINT FK_Appointments_Departments FOREIGN KEY (DepartmentId) REFERENCES Departments(Id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Visits (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    VisitNumber VARCHAR(30) NOT NULL UNIQUE,
    AppointmentId INT NULL UNIQUE,
    PatientId INT NOT NULL,
    DoctorId INT NOT NULL,
    DepartmentId INT NOT NULL,
    VisitDate DATE NOT NULL,
    VisitType VARCHAR(20) NOT NULL,
    TokenNumber INT NOT NULL,
    TokenDisplay VARCHAR(20) NOT NULL,
    Status VARCHAR(30) NOT NULL,
    CheckedInAt DATETIME(6) NULL,
    ConsultationStartedAt DATETIME(6) NULL,
    ConsultationCompletedAt DATETIME(6) NULL,
    CheckedOutAt DATETIME(6) NULL,
    CheckedInByUserId INT NULL,
    CheckedOutByUserId INT NULL,
    ChiefComplaint VARCHAR(500) NULL,
    CancellationReason VARCHAR(500) NULL,
    Notes VARCHAR(1000) NULL,
    CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UpdatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    UNIQUE INDEX UX_Visits_Doctor_Date_Token (DoctorId, VisitDate, TokenNumber),
    INDEX IX_Visits_Date_Status (VisitDate, Status),
    CONSTRAINT FK_Visits_Appointments FOREIGN KEY (AppointmentId) REFERENCES Appointments(Id) ON DELETE RESTRICT,
    CONSTRAINT FK_Visits_Patients FOREIGN KEY (PatientId) REFERENCES Patients(Id) ON DELETE RESTRICT,
    CONSTRAINT FK_Visits_Doctors FOREIGN KEY (DoctorId) REFERENCES Doctors(Id) ON DELETE RESTRICT,
    CONSTRAINT FK_Visits_Departments FOREIGN KEY (DepartmentId) REFERENCES Departments(Id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Consultations (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    VisitId INT NOT NULL UNIQUE,
    DoctorId INT NOT NULL,
    PatientId INT NOT NULL,
    Status VARCHAR(25) NOT NULL,
    Symptoms VARCHAR(2000) NOT NULL,
    BloodPressure VARCHAR(25) NULL,
    TemperatureCelsius DECIMAL(4,1) NULL,
    PulseRate INT NULL,
    RespiratoryRate INT NULL,
    SpO2 INT NULL,
    WeightKg DECIMAL(5,2) NULL,
    HeightCm DECIMAL(5,2) NULL,
    ClinicalExamination VARCHAR(2000) NULL,
    Diagnosis VARCHAR(1000) NOT NULL DEFAULT '',
    IcdCode VARCHAR(20) NULL,
    ConsultationNotes VARCHAR(2000) NULL,
    FollowUpInstructions VARCHAR(1000) NULL,
    RecommendedFollowUpDate DATE NULL,
    StartedAt DATETIME(6) NOT NULL,
    CompletedAt DATETIME(6) NULL,
    CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UpdatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    CONSTRAINT FK_Consultations_Visits FOREIGN KEY (VisitId) REFERENCES Visits(Id) ON DELETE RESTRICT,
    CONSTRAINT FK_Consultations_Doctors FOREIGN KEY (DoctorId) REFERENCES Doctors(Id) ON DELETE RESTRICT,
    CONSTRAINT FK_Consultations_Patients FOREIGN KEY (PatientId) REFERENCES Patients(Id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Prescriptions (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    PrescriptionNumber VARCHAR(30) NOT NULL UNIQUE,
    ConsultationId INT NOT NULL UNIQUE,
    VisitId INT NOT NULL,
    DoctorId INT NOT NULL,
    PatientId INT NOT NULL,
    GeneralInstructions VARCHAR(1000) NULL,
    IssuedAt DATETIME(6) NOT NULL,
    CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UpdatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    CONSTRAINT FK_Prescriptions_Consultations FOREIGN KEY (ConsultationId) REFERENCES Consultations(Id) ON DELETE CASCADE,
    CONSTRAINT FK_Prescriptions_Visits FOREIGN KEY (VisitId) REFERENCES Visits(Id) ON DELETE RESTRICT,
    CONSTRAINT FK_Prescriptions_Doctors FOREIGN KEY (DoctorId) REFERENCES Doctors(Id) ON DELETE RESTRICT,
    CONSTRAINT FK_Prescriptions_Patients FOREIGN KEY (PatientId) REFERENCES Patients(Id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS PrescriptionItems (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    PrescriptionId INT NOT NULL,
    MedicineName VARCHAR(180) NOT NULL,
    Dosage VARCHAR(80) NOT NULL,
    Frequency VARCHAR(80) NOT NULL,
    DurationDays INT NOT NULL,
    Route VARCHAR(50) NOT NULL DEFAULT 'Oral',
    TimingInstruction VARCHAR(120) NULL,
    Quantity INT NULL,
    Notes VARCHAR(300) NULL,
    CONSTRAINT FK_PrescriptionItems_Prescriptions FOREIGN KEY (PrescriptionId) REFERENCES Prescriptions(Id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Bills (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    BillNumber VARCHAR(30) NOT NULL UNIQUE,
    VisitId INT NOT NULL UNIQUE,
    PatientId INT NOT NULL,
    GeneratedByUserId INT NULL,
    SubTotal DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    DiscountAmount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    TaxAmount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    TotalAmount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    PaidAmount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    BalanceAmount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    Status VARCHAR(25) NOT NULL,
    Notes VARCHAR(500) NULL,
    IssuedAt DATETIME(6) NOT NULL,
    CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UpdatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    INDEX IX_Bills_Status (Status),
    CONSTRAINT FK_Bills_Visits FOREIGN KEY (VisitId) REFERENCES Visits(Id) ON DELETE RESTRICT,
    CONSTRAINT FK_Bills_Patients FOREIGN KEY (PatientId) REFERENCES Patients(Id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS BillItems (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    BillId INT NOT NULL,
    ServiceCode VARCHAR(30) NOT NULL,
    Description VARCHAR(250) NOT NULL,
    Category VARCHAR(25) NOT NULL,
    Quantity INT NOT NULL DEFAULT 1,
    UnitPrice DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    TotalPrice DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    CONSTRAINT FK_BillItems_Bills FOREIGN KEY (BillId) REFERENCES Bills(Id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Payments (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    ReceiptNumber VARCHAR(30) NOT NULL UNIQUE,
    BillId INT NOT NULL,
    PatientId INT NOT NULL,
    Amount DECIMAL(12,2) NOT NULL,
    Method VARCHAR(25) NOT NULL,
    Status VARCHAR(25) NOT NULL,
    TransactionReference VARCHAR(120) NULL,
    GatewayOrderId VARCHAR(120) NULL,
    GatewayPaymentId VARCHAR(120) NULL,
    RecordedByUserId INT NULL,
    PaidAt DATETIME(6) NOT NULL,
    Notes VARCHAR(500) NULL,
    CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UpdatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    INDEX IX_Payments_PaidAt (PaidAt),
    CONSTRAINT FK_Payments_Bills FOREIGN KEY (BillId) REFERENCES Bills(Id) ON DELETE RESTRICT,
    CONSTRAINT FK_Payments_Patients FOREIGN KEY (PatientId) REFERENCES Patients(Id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Notifications (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    UserId INT NOT NULL,
    Title VARCHAR(150) NOT NULL,
    Message VARCHAR(1000) NOT NULL,
    Type VARCHAR(30) NOT NULL,
    RelatedEntityType VARCHAR(60) NULL,
    RelatedEntityId INT NULL,
    IsRead TINYINT(1) NOT NULL DEFAULT 0,
    ReadAt DATETIME(6) NULL,
    CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    INDEX IX_Notifications_User_Read (UserId, IsRead, CreatedAt),
    CONSTRAINT FK_Notifications_Users FOREIGN KEY (UserId) REFERENCES Users(Id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS RefreshTokens (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    UserId INT NOT NULL,
    TokenHash VARCHAR(128) NOT NULL UNIQUE,
    JwtId VARCHAR(64) NOT NULL,
    ExpiresAt DATETIME(6) NOT NULL,
    CreatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CreatedByIp VARCHAR(64) NULL,
    RevokedAt DATETIME(6) NULL,
    RevokedByIp VARCHAR(64) NULL,
    ReplacedByTokenHash VARCHAR(128) NULL,
    ReasonRevoked VARCHAR(200) NULL,
    CONSTRAINT FK_RefreshTokens_Users FOREIGN KEY (UserId) REFERENCES Users(Id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS AuditLogs (
    Id BIGINT AUTO_INCREMENT PRIMARY KEY,
    UserId INT NULL,
    UserEmail VARCHAR(160) NULL,
    UserRole VARCHAR(50) NULL,
    Action VARCHAR(80) NOT NULL,
    EntityName VARCHAR(80) NOT NULL,
    EntityId VARCHAR(64) NULL,
    Details VARCHAR(1000) NULL,
    OldValuesJson LONGTEXT NULL,
    NewValuesJson LONGTEXT NULL,
    IpAddress VARCHAR(64) NULL,
    UserAgent VARCHAR(300) NULL,
    Timestamp DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    INDEX IX_AuditLogs_Timestamp (Timestamp),
    INDEX IX_AuditLogs_Entity (EntityName, EntityId)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS HospitalSettings (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    HospitalName VARCHAR(160) NOT NULL,
    Tagline VARCHAR(250) NOT NULL,
    Phone VARCHAR(30) NOT NULL,
    EmergencyPhone VARCHAR(30) NOT NULL,
    Email VARCHAR(160) NOT NULL,
    AddressLine VARCHAR(250) NOT NULL,
    City VARCHAR(100) NOT NULL,
    State VARCHAR(100) NOT NULL,
    PostalCode VARCHAR(20) NOT NULL,
    MapUrl VARCHAR(500) NOT NULL,
    RegistrationFee DECIMAL(10,2) NOT NULL DEFAULT 100.00,
    TaxPercentage DECIMAL(5,2) NOT NULL DEFAULT 0.00,
    CurrencyCode VARCHAR(10) NOT NULL DEFAULT 'INR',
    OpdStartTime TIME(6) NOT NULL DEFAULT '09:00:00',
    OpdEndTime TIME(6) NOT NULL DEFAULT '18:00:00',
    DefaultSlotMinutes INT NOT NULL DEFAULT 15,
    AllowOnlineBooking TINYINT(1) NOT NULL DEFAULT 1,
    RequireFullPaymentBeforeCheckout TINYINT(1) NOT NULL DEFAULT 1,
    UpdatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;
